/**
 * Draw a panel directly into a context (so it can be any size).
 * variant: 'wood' | 'dark' | 'parchment' | 'slate'
 */
export function panel(ctx, x, y, w, h, variant = 'wood') {
  x |= 0; y |= 0; w |= 0; h |= 0;
  const V = {
    wood: { out: '#0b0710', d: C.uiWoodD, m: C.uiWood, l: C.uiWoodL, hi: C.uiWoodHi, fill: C.uiFill, fill2: C.uiFillHi, gold: C.uiGold },
    dark: { out: '#05040a', d: '#1a1426', m: '#241b33', l: '#332745', hi: '#463659', fill: '#100b1a', fill2: '#17102450', gold: '#8f7a3a' },
    parchment: { out: '#241a12', d: '#7a6242', m: '#a8895c', l: '#c9ad7c', hi: '#e3cfa4', fill: '#d9c49a', fill2: '#e8d8b4', gold: '#7a5a24' },
    slate: { out: '#04040a', d: '#191a2c', m: '#23253c', l: '#31344f', hi: '#454a68', fill: '#0e0f1c', fill2: '#15172a', gold: '#5c6ba8' },
  }[variant] || {};

  const R2 = (a, b, c2, d2, col) => { ctx.fillStyle = col; ctx.fillRect(a | 0, b | 0, c2 | 0, d2 | 0); };

  // drop shadow
  ctx.fillStyle = 'rgba(0,0,0,0.45)';
  ctx.fillRect(x + 3, y + 4, w, h);

  // outer border
  R2(x, y, w, h, V.out);
  R2(x + 1, y + 1, w - 2, h - 2, V.d);
  R2(x + 2, y + 2, w - 4, h - 4, V.m);
  // bevel highlight
  R2(x + 2, y + 2, w - 4, 1, V.l);
  R2(x + 2, y + 2, 1, h - 4, V.l);
  R2(x + 2, y + h - 3, w - 4, 1, V.d);
  R2(x + w - 3, y + 2, 1, h - 4, V.d);
  // gold inlay
  R2(x + 4, y + 4, w - 8, 1, V.gold);
  R2(x + 4, y + h - 5, w - 8, 1, V.gold);
  R2(x + 4, y + 4, 1, h - 8, V.gold);
  R2(x + w - 5, y + 4, 1, h - 8, V.gold);
  // inner well
  R2(x + 5, y + 5, w - 10, h - 10, V.out);
  R2(x + 6, y + 6, w - 12, h - 12, V.fill);
  R2(x + 6, y + 6, w - 12, 1, V.fill2);

  // corner studs
  for (const [cx, cy] of [[x + 3, y + 3], [x + w - 6, y + 3], [x + 3, y + h - 6], [x + w - 6, y + h - 6]]) {
    R2(cx, cy, 3, 3, V.hi);
    R2(cx, cy, 2, 2, V.gold);
    R2(cx, cy, 1, 1, '#ffe9a8');
  }
  return { ix: x + 7, iy: y + 7, iw: w - 14, ih: h - 14 };
}

/** Small inset slot (inventory cell). */
export function slot(ctx, x, y, s, selected = false, empty = true) {
  const R2 = (a, b, c2, d2, col) => { ctx.fillStyle = col; ctx.fillRect(a | 0, b | 0, c2 | 0, d2 | 0); };
  R2(x, y, s, s, '#0b0710');
  R2(x + 1, y + 1, s - 2, s - 2, empty ? '#241729' : '#33203a');
  R2(x + 1, y + 1, s - 2, 1, '#181021');
  R2(x + 1, y + s - 2, s - 2, 1, '#432a49');
  if (selected) {
    R2(x - 1, y - 1, s + 2, 1, C.uiGoldHi);
    R2(x - 1, y + s, s + 2, 1, C.uiGoldHi);
    R2(x - 1, y - 1, 1, s + 2, C.uiGoldHi);
    R2(x + s, y - 1, 1, s + 2, C.uiGoldHi);
  }
}

/** Horizontal bar (health / energy) with a carved frame. */
export function bar(ctx, x, y, w, h, t, colA, colB, bg = '#1a0d18') {
  const R2 = (a, b, c2, d2, col) => { ctx.fillStyle = col; ctx.fillRect(a | 0, b | 0, c2 | 0, d2 | 0); };
  R2(x - 1, y - 1, w + 2, h + 2, '#0b0710');
  R2(x, y, w, h, bg);
  const fw = Math.max(0, Math.round(w * Math.max(0, Math.min(1, t))));
  if (fw > 0) {
    R2(x, y, fw, h, colB);
    R2(x, y, fw, Math.max(1, (h / 2) | 0), colA);
    R2(x, y, fw, 1, '#ffffff44');
  }
}
