const GW = 5, GH = 7;
const cache = new Map();

function glyphCanvas(ch, col) {
  const key = ch + col;
  let c = cache.get(key);
  if (c) return c;
  const g = GLYPHS[ch] || GLYPHS['?'];
  const rows = g.split('/');
  const p = new P(GW, GH);
  for (let y = 0; y < GH; y++)
    for (let x = 0; x < GW; x++)
      if (rows[y][x] === '#') p.px(x, y, col);
  cache.set(key, p.canvas);
  return p.canvas;
}

export function textWidth(str, scale = 1, tracking = 1) {
  return str.length * (GW + tracking) * scale - tracking * scale;
}

/**
 * Draw text into a 2d context at integer coords.
 * opts: { color, shadow, scale, tracking, align, maxW }
 */
export function drawText(ctx, str, x, y, opts = {}) {
  const col = opts.color || C.text;
  const sc = opts.scale || 1;
  const tr = opts.tracking != null ? opts.tracking : 1;
  const shadow = opts.shadow === undefined ? '#150c14' : opts.shadow;
  let w = textWidth(str, sc, tr);
  let ox = x;
  if (opts.align === 'center') ox = Math.round(x - w / 2);
  else if (opts.align === 'right') ox = Math.round(x - w);
  ox = ox | 0; y = y | 0;

  for (let i = 0; i < str.length; i++) {
    const ch = str[i];
    if (ch !== ' ') {
      if (shadow) {
        const sg = glyphCanvas(ch, shadow);
        ctx.drawImage(sg, 0, 0, GW, GH, ox + sc, y + sc, GW * sc, GH * sc);
      }
      const g = glyphCanvas(ch, col);
      ctx.drawImage(g, 0, 0, GW, GH, ox, y, GW * sc, GH * sc);
    }
    ox += (GW + tr) * sc;
  }
  return w;
}

/** Word-wrap helper. Returns array of lines. */
export function wrapText(str, maxW, scale = 1, tracking = 1) {
  const words = str.split(' ');
  const lines = [];
  let cur = '';
  for (const wd of words) {
    const test = cur ? cur + ' ' + wd : wd;
    if (textWidth(test, scale, tracking) > maxW && cur) { lines.push(cur); cur = wd; }
    else cur = test;
  }
  if (cur) lines.push(cur);
  return lines;
}

